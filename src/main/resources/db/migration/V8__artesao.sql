ALTER TABLE USUARIO DROP CONSTRAINT CK_USUARIO_ROLE;
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_ROLE CHECK (ROLE IN ('ADMIN', 'USER', 'ARTESAO'));

-- Preenchido = atelie de um artesao; nulo = ecoponto
ALTER TABLE PONTO_COLETA
    ADD COLUMN ID_USUARIO_ARTESAO BIGINT,
    ADD CONSTRAINT UK_PONTO_ARTESAO UNIQUE (ID_USUARIO_ARTESAO),
    ADD CONSTRAINT FK_PONTO_ARTESAO FOREIGN KEY (ID_USUARIO_ARTESAO) REFERENCES USUARIO (ID_USUARIO);

ALTER TABLE TRANSACAO_MOEDA DROP CONSTRAINT CK_TRANSACAO_TIPO;
ALTER TABLE TRANSACAO_MOEDA ADD CONSTRAINT CK_TRANSACAO_TIPO
    CHECK (TIPO IN ('CREDITO', 'VOUCHER', 'TRANSFERENCIA', 'COMPRA', 'VENDA'));

CREATE SEQUENCE SEQ_PRODUTO START WITH 1 INCREMENT BY 1;
CREATE TABLE PRODUTO (
    ID_PRODUTO       BIGINT          NOT NULL,
    ID_PONTO_COLETA  BIGINT          NOT NULL,
    NOME             VARCHAR(120)    NOT NULL,
    DESCRICAO        VARCHAR(1000),
    PRECO_REAIS      NUMERIC(10,2)   NOT NULL,
    PRECO_MOEDAS     NUMERIC(10,2),
    IMAGEM           BYTEA,
    DATA_CRIACAO     TIMESTAMP       NOT NULL,
    DATA_ATUALIZACAO TIMESTAMP,
    CONSTRAINT PK_PRODUTO PRIMARY KEY (ID_PRODUTO),
    CONSTRAINT FK_PRODUTO_PONTO FOREIGN KEY (ID_PONTO_COLETA) REFERENCES PONTO_COLETA (ID_PONTO_COLETA),
    CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO_REAIS > 0 AND (PRECO_MOEDAS IS NULL OR PRECO_MOEDAS > 0))
);

