-- Códigos de demonstração, os mesmos do protótipo web. Valem para qualquer conta, quantas vezes quiser:
-- CarteiraService cria uma entrega nova a cada leitura, então o código nunca fica marcado como usado.
ALTER TABLE ENTREGA_QR ADD COLUMN DEMO CHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE ENTREGA_QR ADD CONSTRAINT CK_ENTREGA_QR_DEMO CHECK (DEMO IN ('S', 'N'));

-- ECO-4821: 3 kg de plástico; ECO-7310: 1,2 kg de metal (primeiro ecoponto de cada material)
INSERT INTO ENTREGA_QR (ID_ENTREGA_QR, CODIGO, ID_PONTO_COLETA, ID_TIPO_RESIDUO, QUANTIDADE_KG, DATA_CRIACAO, DEMO)
SELECT nextval('SEQ_ENTREGA_QR'), v.CODIGO, p.ID_PONTO_COLETA, t.ID_TIPO_RESIDUO, v.KG, NOW(), 'S'
FROM (VALUES ('ECO-4821', 'PLASTICO', 3.00), ('ECO-7310', 'METAL', 1.20)) AS v(CODIGO, NOME, KG)
JOIN TIPO_RESIDUO t ON t.NOME = v.NOME
JOIN PONTO_COLETA p ON p.ID_PONTO_COLETA = (
    SELECT MIN(ID_PONTO_COLETA) FROM PONTO_COLETA
    WHERE ID_TIPO_RESIDUO = t.ID_TIPO_RESIDUO AND ID_USUARIO_ARTESAO IS NULL);

-- ATL-0550: 2 kg no primeiro ateliê de artesão (rende +50% e o cupom)
INSERT INTO ENTREGA_QR (ID_ENTREGA_QR, CODIGO, ID_PONTO_COLETA, ID_TIPO_RESIDUO, QUANTIDADE_KG, DATA_CRIACAO, DEMO)
SELECT nextval('SEQ_ENTREGA_QR'), 'ATL-0550', p.ID_PONTO_COLETA, p.ID_TIPO_RESIDUO, 2.00, NOW(), 'S'
FROM PONTO_COLETA p
WHERE p.ID_PONTO_COLETA = (SELECT MIN(ID_PONTO_COLETA) FROM PONTO_COLETA WHERE ID_USUARIO_ARTESAO IS NOT NULL);
