-- Histórico de demonstração: cada conta ativa sem movimentações ganha entregas e um voucher.
-- Os valores mudam por conta (3 perfis, repetidos se houver mais contas).
-- Grava descarte (soma os kg), transação (aparece no histórico) e saldo, como CarteiraService faz numa entrega real.

CREATE TEMP TABLE DEMO_USUARIO AS
SELECT u.ID_USUARIO, (ROW_NUMBER() OVER (ORDER BY u.ID_USUARIO) - 1) % 3 + 1 AS PERFIL
FROM USUARIO u
WHERE u.ATIVO = 'S'
  AND NOT EXISTS (SELECT 1 FROM TRANSACAO_MOEDA t WHERE t.ID_USUARIO = u.ID_USUARIO);

-- Entregas de cada perfil, no primeiro ponto de coleta do material (os ecopontos do seed)
CREATE TEMP TABLE DEMO_ENTREGA AS
SELECT v.PERFIL,
       tr.ID_TIPO_RESIDUO,
       (SELECT MIN(p.ID_PONTO_COLETA) FROM PONTO_COLETA p WHERE p.ID_TIPO_RESIDUO = tr.ID_TIPO_RESIDUO) AS ID_PONTO_COLETA,
       v.KG,
       v.DIAS,
       v.KG * tr.MOEDAS_POR_KG AS MOEDAS
FROM (VALUES
        (1, 'PLASTICO', 6.00, 9), (1, 'PAPEL', 4.00, 6), (1, 'VIDRO', 2.40, 3),
        (2, 'PAPEL', 8.00, 12), (2, 'PLASTICO', 3.20, 7), (2, 'METAL', 1.50, 2),
        (3, 'PLASTICO', 2.00, 15), (3, 'VIDRO', 5.00, 10), (3, 'PAPEL', 2.50, 5), (3, 'METAL', 0.80, 4)
     ) AS v(PERFIL, NOME, KG, DIAS)
JOIN TIPO_RESIDUO tr ON tr.NOME = v.NOME;

DELETE FROM DEMO_ENTREGA WHERE ID_PONTO_COLETA IS NULL;

-- Voucher de cada perfil: valor e comércio (pela ordem de cadastro) diferentes
CREATE TEMP TABLE DEMO_VOUCHER AS
SELECT v.PERFIL, v.VALOR, v.DIAS, c.ID_COMERCIO, c.NOME
FROM (VALUES (1, 10.00, 1, 1), (2, 15.00, 1, 2), (3, 5.00, 2, 3)) AS v(PERFIL, VALOR, DIAS, ORDEM)
JOIN (SELECT ID_COMERCIO, NOME, ROW_NUMBER() OVER (ORDER BY ID_COMERCIO) AS ORDEM FROM COMERCIO) c ON c.ORDEM = v.ORDEM;

INSERT INTO DESCARTE (ID_DESCARTE, ID_PONTO_COLETA, ID_TIPO_RESIDUO, DATA_DESCARTE, QUANTIDADE_KG, ORIGEM, DESCARTE_CORRETO, ID_USUARIO)
SELECT nextval('SEQ_DESCARTE'), e.ID_PONTO_COLETA, e.ID_TIPO_RESIDUO, CURRENT_DATE - e.DIAS, e.KG, 'App EcoCiclo', 'S', u.ID_USUARIO
FROM DEMO_USUARIO u JOIN DEMO_ENTREGA e ON e.PERFIL = u.PERFIL;

INSERT INTO TRANSACAO_MOEDA (ID_TRANSACAO, ID_USUARIO, TIPO, VALOR, DESCRICAO, DATA_TRANSACAO)
SELECT nextval('SEQ_TRANSACAO_MOEDA'), u.ID_USUARIO, 'CREDITO', e.MOEDAS,
       'Entrega de ' || e.KG || ' kg em ' || p.NOME,
       NOW() - e.DIAS * INTERVAL '1 day'
FROM DEMO_USUARIO u
JOIN DEMO_ENTREGA e ON e.PERFIL = u.PERFIL
JOIN PONTO_COLETA p ON p.ID_PONTO_COLETA = e.ID_PONTO_COLETA;

-- Código único como o da API: 12 caracteres
INSERT INTO TRANSACAO_MOEDA (ID_TRANSACAO, ID_USUARIO, TIPO, VALOR, DESCRICAO, ID_COMERCIO, CODIGO_VOUCHER, DATA_TRANSACAO)
SELECT nextval('SEQ_TRANSACAO_MOEDA'), u.ID_USUARIO, 'VOUCHER', v.VALOR, 'Voucher para ' || v.NOME, v.ID_COMERCIO,
       UPPER(SUBSTRING(MD5(u.ID_USUARIO || '-' || CLOCK_TIMESTAMP()::TEXT || RANDOM()::TEXT) FROM 1 FOR 12)),
       NOW() - v.DIAS * INTERVAL '1 day'
FROM DEMO_USUARIO u JOIN DEMO_VOUCHER v ON v.PERFIL = u.PERFIL;

UPDATE USUARIO u
SET SALDO_ECOMOEDAS = u.SALDO_ECOMOEDAS
    + (SELECT COALESCE(SUM(e.MOEDAS), 0) FROM DEMO_ENTREGA e WHERE e.PERFIL = d.PERFIL)
    - (SELECT COALESCE(SUM(v.VALOR), 0) FROM DEMO_VOUCHER v WHERE v.PERFIL = d.PERFIL)
FROM DEMO_USUARIO d
WHERE u.ID_USUARIO = d.ID_USUARIO;

DROP TABLE DEMO_VOUCHER;
DROP TABLE DEMO_ENTREGA;
DROP TABLE DEMO_USUARIO;
