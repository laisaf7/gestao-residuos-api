CREATE SEQUENCE SEQ_COMERCIO START WITH 1 INCREMENT BY 1;
CREATE TABLE COMERCIO (
    ID_COMERCIO     BIGINT      NOT NULL,
    NOME            VARCHAR(120)   NOT NULL,
    CATEGORIA       VARCHAR(50)    NOT NULL,
    DESCRICAO       VARCHAR(300),
    ENDERECO        VARCHAR(200),
    BAIRRO          VARCHAR(100),
    SALDO_RECEBIDO  NUMERIC(12,2)    DEFAULT 0 NOT NULL,
    ATIVO           CHAR(1)         DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_COMERCIO PRIMARY KEY (ID_COMERCIO),
    CONSTRAINT CK_COMERCIO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE SEQUENCE SEQ_ENTREGA_QR START WITH 1 INCREMENT BY 1;
CREATE TABLE ENTREGA_QR (
    ID_ENTREGA_QR       BIGINT      NOT NULL,
    CODIGO              VARCHAR(36)    NOT NULL,
    ID_PONTO_COLETA     BIGINT      NOT NULL,
    ID_TIPO_RESIDUO     BIGINT      NOT NULL,
    QUANTIDADE_KG       NUMERIC(10,2)    NOT NULL,
    DATA_CRIACAO        TIMESTAMP       NOT NULL,
    ID_USUARIO_RESGATE  BIGINT,
    DATA_RESGATE        TIMESTAMP,
    CONSTRAINT PK_ENTREGA_QR PRIMARY KEY (ID_ENTREGA_QR),
    CONSTRAINT UK_ENTREGA_QR_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_ENTREGA_QR_PONTO FOREIGN KEY (ID_PONTO_COLETA) REFERENCES PONTO_COLETA (ID_PONTO_COLETA),
    CONSTRAINT FK_ENTREGA_QR_TIPO FOREIGN KEY (ID_TIPO_RESIDUO) REFERENCES TIPO_RESIDUO (ID_TIPO_RESIDUO),
    CONSTRAINT FK_ENTREGA_QR_USUARIO FOREIGN KEY (ID_USUARIO_RESGATE) REFERENCES USUARIO (ID_USUARIO)
);

CREATE SEQUENCE SEQ_TRANSACAO_MOEDA START WITH 1 INCREMENT BY 1;
CREATE TABLE TRANSACAO_MOEDA (
    ID_TRANSACAO    BIGINT      NOT NULL,
    ID_USUARIO      BIGINT      NOT NULL,
    TIPO            VARCHAR(20)    NOT NULL,
    VALOR           NUMERIC(12,2)    NOT NULL,
    DESCRICAO       VARCHAR(200)   NOT NULL,
    ID_COMERCIO     BIGINT,
    CODIGO_VOUCHER  VARCHAR(12),
    DATA_TRANSACAO  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_TRANSACAO_MOEDA PRIMARY KEY (ID_TRANSACAO),
    CONSTRAINT UK_TRANSACAO_VOUCHER UNIQUE (CODIGO_VOUCHER),
    CONSTRAINT CK_TRANSACAO_TIPO CHECK (TIPO IN ('CREDITO', 'VOUCHER', 'TRANSFERENCIA')),
    CONSTRAINT FK_TRANSACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_TRANSACAO_COMERCIO FOREIGN KEY (ID_COMERCIO) REFERENCES COMERCIO (ID_COMERCIO)
);

